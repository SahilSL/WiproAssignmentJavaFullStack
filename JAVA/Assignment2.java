package com.wipro.practice;


// using assignment operators (eg. +=, -=, *=)

public class Assignment2 {
	public static void main(String[] args) {
        int num = 2345;

        num += 8;     
        num /= 3;     
        num %= 5;     
        num *= 5;     

        System.out.println("Final result :: " + num);
    }
}

//Final result :: 20
